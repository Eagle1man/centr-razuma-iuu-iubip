/* Проверка корректора опечаток (T-1045): «медецина» -> «медицина».
   Запуск: npx tsx scripts/typo_check.ts (или в составе сборки). */

import { fixTypos, normalize, stem } from '../src/lib/fuzzySearch'

let failed = 0

function check(name: string, cond: boolean, extra = ''): void {
  if (cond) {
    console.log('OK   ' + name)
  } else {
    failed += 1
    console.log('FAIL ' + name + ' ' + extra)
  }
}

// Ошибки, которые пользователь реально набирает
check('медецина -> медицина', fixTypos('медецина') === 'медицина', fixTypos('медецина'))
check('фармаколгя -> фармакология', fixTypos('фармаколгя') === 'фармакология', fixTypos('фармаколгя'))
check('психлогия -> психология', fixTypos('психлогия') === 'психология', fixTypos('психлогия'))
check('бухгалтерия без опечатки не меняется', fixTypos('бухгалтерия') === 'бухгалтерия')
check('бухучет -> бухучёт-стем', normalize(fixTypos('бухучет')).includes('бухуч'), fixTypos('бухучет'))
check('ошибка в нескольких словах', fixTypos('медецина и фармаколгя') === 'медицина и фармакология', fixTypos('медецина и фармаколгя'))

// То, что трогать НЕЛЬЗЯ: короткие слова и реально другие слова
check('правоведение не ломается', fixTypos('правоведение') === 'правоведение', fixTypos('правоведение'))
check('короткое слово не меняется', fixTypos('право') === 'право')
check('несвязанное слово не меняется', fixTypos('компьютер') === 'компьютер', fixTypos('компьютер'))
check('пустая строка безопасна', fixTypos('') === '')

// Словарь направлений расширяет словарь
check('доп. слово из тегов чинится', fixTypos('гостеприимст', ['гостеприимство']) === 'гостеприимство', fixTypos('гостеприимст', ['гостеприимство']))

// Нормализация и стемминг не сломались
check('ё -> е', normalize('ПРАВО и ёж') === 'право и еж')
check('стем длинного слова', stem('фармакология') === 'фармаколог', stem('фармакология'))

console.log('\n' + (failed === 0 ? 'ВСЕ ТЕСТЫ ПРОЙДЕНЫ' : 'ПРОВАЛЕНО: ' + failed))
process.exit(failed ? 1 : 0)